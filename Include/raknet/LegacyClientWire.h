[[nodiscard]] constexpr bool EncodeClientDatagram(
    const std::uint8_t* source,
    const std::size_t sourceSize,
    const std::uint16_t destinationPort,
    std::uint8_t* destination,
    const std::size_t destinationCapacity) noexcept {
    if (source == nullptr || destination == nullptr || destinationCapacity < sourceSize + 1u) {
        return false;
    }

    std::uint8_t checksum{};
    const auto portMask{ static_cast<std::uint8_t>(destinationPort ^ 0xCCu) };
    for (std::size_t i = 0; i < sourceSize; ++i) {
        const auto plain{ source[i] };
        checksum ^= plain & 0xAAu;

        auto encoded{ kInverseServerDecodeKey[plain] };
        // Server Decrypt XORs even wire indices before its lookup.  The wire
        // index is the source index plus one, so the inverse XOR belongs after
        // the lookup for odd source indices.
        if ((i & 1u) != 0u) {
            encoded ^= portMask;
        }
        destination[i + 1u] = encoded;
    }
    destination[0] = checksum;
    return true;
}

